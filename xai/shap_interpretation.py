import os
import pandas as pd


# ============================================================
# SHAP INTERPRETATION REPORT
# ============================================================

print("=" * 75)
print("             SHAP INTERPRETATION REPORT")
print("=" * 75)


# ============================================================
# PATHS
# ============================================================

RESULTS_DIR = "xai/results"

FEATURE_FILE = os.path.join(
    RESULTS_DIR,
    "feature_importance.csv"
)

INDIVIDUAL_FILE = os.path.join(
    RESULTS_DIR,
    "individual_explanation.txt"
)

OUTPUT_FILE = os.path.join(
    RESULTS_DIR,
    "shap_interpretation_report.txt"
)


# ============================================================
# LOAD GLOBAL FEATURE IMPORTANCE
# ============================================================

print("\n[1] Loading global SHAP feature importance...")

feature_df = pd.read_csv(
    FEATURE_FILE
)

feature_df = feature_df.sort_values(
    "mean_abs_shap",
    ascending=False
)

print(
    "Features loaded:",
    len(feature_df)
)


# ============================================================
# TOP 20 FEATURES
# ============================================================

top20 = feature_df.head(20)


print("\n[2] TOP 20 IMPORTANT FEATURES")
print("-" * 75)

print(
    top20.to_string(index=False)
)


# ============================================================
# LOAD INDIVIDUAL EXPLANATION
# ============================================================

print("\n[3] Loading individual attack explanation...")

with open(
    INDIVIDUAL_FILE,
    "r",
    encoding="utf-8"
) as file:

    individual_text = file.read()

print(
    "Individual explanation loaded successfully."
)


# ============================================================
# CREATE REPORT
# ============================================================

print("\n[4] Creating interpretation report...")


with open(
    OUTPUT_FILE,
    "w",
    encoding="utf-8"
) as report:

    report.write(
        "EXPLAINABLE AI (SHAP) INTERPRETATION REPORT\n"
    )

    report.write(
        "=" * 75 + "\n\n"
    )

    # --------------------------------------------------------
    # INTRODUCTION
    # --------------------------------------------------------

    report.write(
        "1. PURPOSE OF SHAP ANALYSIS\n"
    )

    report.write(
        "-" * 50 + "\n"
    )

    report.write(
        "SHAP (SHapley Additive exPlanations) was used to "
        "interpret the predictions generated by the XGBoost "
        "network intrusion detection model. The analysis "
        "identifies the features that contribute most strongly "
        "to model predictions and provides an explanation for "
        "an individual attack prediction.\n\n"
    )

    # --------------------------------------------------------
    # GLOBAL ANALYSIS
    # --------------------------------------------------------

    report.write(
        "2. GLOBAL FEATURE IMPORTANCE\n"
    )

    report.write(
        "-" * 50 + "\n"
    )

    report.write(
        "The following features had the highest mean absolute "
        "SHAP values in the analyzed test sample. A higher "
        "mean absolute SHAP value indicates a larger average "
        "contribution to the model's predictions.\n\n"
    )

    report.write(
        top20.to_string(index=False)
    )

    report.write("\n\n")

    # --------------------------------------------------------
    # TOP 10
    # --------------------------------------------------------

    report.write(
        "3. TOP 10 MOST INFLUENTIAL FEATURES\n"
    )

    report.write(
        "-" * 50 + "\n"
    )

    for index, row in top20.head(10).iterrows():

        rank = index + 1

        report.write(
            f"{rank}. {row['feature']} "
            f"- Mean |SHAP| = "
            f"{row['mean_abs_shap']:.6f}\n"
        )

    report.write("\n")

    # --------------------------------------------------------
    # INDIVIDUAL EXPLANATION
    # --------------------------------------------------------

    report.write(
        "4. INDIVIDUAL ATTACK EXPLANATION\n"
    )

    report.write(
        "-" * 50 + "\n"
    )

    report.write(
        individual_text
    )

    report.write("\n\n")

    # --------------------------------------------------------
    # INTERPRETATION
    # --------------------------------------------------------

    report.write(
        "5. INTERPRETATION\n"
    )

    report.write(
        "-" * 50 + "\n"
    )

    report.write(
        "The SHAP analysis demonstrates how Explainable AI "
        "can be applied to a network intrusion detection model. "
        "Instead of providing only a binary prediction, the "
        "SHAP method identifies the input features that "
        "contributed to the prediction. This provides greater "
        "transparency into the behavior of the XGBoost model.\n\n"
    )

    report.write(
        "For the individual analyzed attack record, the SHAP "
        "values show which transformed network features "
        "contributed positively or negatively to the model "
        "prediction. Positive SHAP contributions indicate "
        "movement toward the attack prediction, while negative "
        "contributions indicate movement away from it.\n\n"
    )

    # --------------------------------------------------------
    # RESEARCH SIGNIFICANCE
    # --------------------------------------------------------

    report.write(
        "6. RESEARCH SIGNIFICANCE\n"
    )

    report.write(
        "-" * 50 + "\n"
    )

    report.write(
        "The combination of XGBoost and SHAP provides both "
        "predictive modeling and interpretability. The model "
        "can classify network activity while SHAP provides "
        "information about the features influencing those "
        "predictions. This is particularly relevant for "
        "cybersecurity applications where analysts may need "
        "to understand why network activity was classified "
        "as malicious.\n\n"
    )

    report.write(
        "Note: SHAP feature importance indicates model behavior "
        "and feature contribution. It should not automatically "
        "be interpreted as proof that a feature independently "
        "causes an intrusion.\n"
    )


# ============================================================
# COMPLETE
# ============================================================

print("\nReport saved to:")
print(OUTPUT_FILE)

print("\n" + "=" * 75)
print("          SHAP INTERPRETATION COMPLETE ✓")
print("=" * 75)